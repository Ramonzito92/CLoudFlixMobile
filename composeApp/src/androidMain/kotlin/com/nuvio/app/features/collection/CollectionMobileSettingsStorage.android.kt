    fun initialize(context: Context) {
        val prefs = context.getSharedPreferences(preferencesName, Context.MODE_PRIVATE)
        preferences = prefs
        val scopedKey = ProfileScopedKey.of(payloadKey)
        val existing = prefs.getString(scopedKey, null)
        if (existing.isNullOrBlank() || existing == "[]" || !existing.contains("collection-franquias")) {
            prefs.edit().putString(scopedKey, defaultCollectionsPayload).apply()
        }
    }

    actual fun loadPayload(): String? {
        val saved = preferences?.getString(ProfileScopedKey.of(payloadKey), null)
        return if (saved.isNullOrBlank() || saved == "[]" || !saved.contains("collection-franquias")) {
            defaultCollectionsPayload
        } else {
            saved
        }
    }

    actual fun savePayload(payload: String) {
        preferences
            ?.edit()
            ?.putString(ProfileScopedKey.of(payloadKey), payload)
            ?.apply()
    }
